 # Retain experimental model provenance and reproducible downloads, not unused weights or generated audio.
 files={f for f in files if not (any(part in {'separation-candidates','evaluation-1.6'} for part in f.relative_to(p).parts) and f.suffix.lower() in {'.onnx','.th','.pt','.pth','.f32','.wav','.mp3','.zip','.npz','.npy'})}
 require(all(distributable(f,p) for f in files),'A non-distributable source item was selected.')
 root=f'LightForge-{VERSION}/'
