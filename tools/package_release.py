 require(not missing,'Current release evidence missing; finish validation before packaging: '+', '.join(missing))
 results={f:json.loads((p/f).read_text()) for f in current_receipts}
 for rel,result in results.items():
  require(result.get('passed') is not False, 'Current test receipt reports failure: '+rel)
  require(not result.get('errors'), 'Current test receipt has errors: '+rel)
  if 'release' in result:require(result['release']==VERSION,'Current receipt belongs to another release: '+rel)
  if rel in music_receipts:
   require(result.get('release')==VERSION and result.get('passed') is True,'Music verification must explicitly pass for '+VERSION+': '+rel)
   require(bool(result.get('source_hashes',result.get('sourceHashes'))),'Music verification must identify its tested production sources: '+rel)
  for source,digest in result.get('source_hashes',result.get('sourceHashes',{})).items():
   require((p/source).is_file() and sha_file(p/source)==digest,'Source changed since verification: '+source+' ('+rel+')')
 # Bind trained model evidence to the exact graphs delivered in this APK.
 model_receipt=results[f'qa/release-{VERSION}/analysis-verification.json']
 for name,details in model_receipt.get('models',{}).items():
  model=p/'web/analysis/models'/name
  require(model.is_file() and sha_file(model)==details['sha256'],'Model changed since runtime verification: '+name)
  require(model.stat().st_size==details['bytes'],'Model byte size changed: '+name)
 historical_paths={
  '1.5.0':'qa/release-1.6.0/historical-release-verification-1.5.0.json',
  '1.4.0':'qa/release-1.5.0/historical-release-verification-1.4.0.json',
  '1.3.0':'qa/release-1.4.0/historical-release-verification-1.3.0.json',
  '1.1.0':'qa/hardware-1.2.0/historical-release-verification-1.1.0.json',
  '1.2.0':'qa/music-1.3.0/historical-release-verification-1.2.0.json'
 }
 historical={}
 for version,rel in historical_paths.items():
  require((p/rel).is_file(),'Historical '+version+' receipt snapshot is missing.')
  prior=json.loads((p/rel).read_text())
  require(prior.get('release',{}).get('version_name')==version,'Historical receipt is not the original '+version+' release.')
