#!/usr/bin/env python3
"""Verify a built release, then atomically publish APK and complete private source."""
from pathlib import Path
import hashlib,json,os,tempfile,zipfile

SIGNING_SHA256='7187d6aa935d5b7d2d656cb87913af95fe1ca3a4b1653036d1d8d890e2016c6b'
CHUNK_BYTES=1024*1024

def sha(data):return hashlib.sha256(data).hexdigest()
def sha_stream(stream):
 digest=hashlib.sha256()
 while True:
  chunk=stream.read(CHUNK_BYTES)
  if not chunk:break
  digest.update(chunk)
 return digest.hexdigest()
def sha_file(path):
 with path.open('rb') as stream:return sha_stream(stream)
def distributable(f,root):
 return f.is_file() and not any(v.startswith('.') or v in {'node_modules','__pycache__','classes'} for v in f.relative_to(root).parts)
def qa_distributable(f,root,qa_root):
 if not distributable(f,root):return False
 if any(v in {'fixtures','generated','node_modules','classes'} or v.endswith('-classes') or v.endswith('-fixtures') for v in f.relative_to(qa_root).parts):return False
 suffixes={'.java','.py','.js','.cjs','.mjs','.html','.json','.md','.txt','.png','.jpg','.webp'}
 if qa_root==root/'qa/release-1.6.0':suffixes.add('.log')
 return f.suffix in suffixes
def atomic(path,data):
 fd,name=tempfile.mkstemp(prefix='.'+path.name+'-',dir=path.parent)
 try:
  with os.fdopen(fd,'wb') as f:f.write(data);f.flush();os.fsync(f.fileno())
  os.replace(name,path)
 finally:
  if os.path.exists(name):os.unlink(name)
def require(condition,message):
 if not condition:raise SystemExit(message)
def streams_match(left,right):
 # Read each side with explicit bounds, retaining exact byte comparison.
 while True:
  a=left.read(CHUNK_BYTES);b=right.read(CHUNK_BYTES)
  if a!=b:return False
  if not a:return True

def atomic_copy(source,destination,expected_sha256):
 """Copy an already verified APK without retaining it in Python's heap."""
 fd,name=tempfile.mkstemp(prefix='.'+destination.name+'-',dir=destination.parent)
 digest=hashlib.sha256();size=0
 try:
  with os.fdopen(fd,'wb') as output,source.open('rb') as input:
   while True:
    chunk=input.read(CHUNK_BYTES)
    if not chunk:break
    output.write(chunk);digest.update(chunk);size+=len(chunk)
   output.flush();os.fsync(output.fileno())
  require(digest.hexdigest()==expected_sha256,'APK changed while publishing; the previous output was retained.')
  os.replace(name,destination)
  return {'path':str(destination),'bytes':size,'sha256':digest.hexdigest()}
 finally:
  if os.path.exists(name):os.unlink(name)

def stage_source_archive(destination,root,entries):
 """Return a CRC-checked temporary ZIP; caller publishes only after all checks.

 Entries are Path objects or small generated bytes. The manifest hashes the
 exact archived bytes, and a changed file aborts before atomic publication.
 """
 require(all(name.startswith(root) for name in entries),'Source entry is outside its archive root.')
 manifest_name=root+'SHA256SUMS.txt'
 require(manifest_name not in entries,'Source entries must not include a preexisting SHA256SUMS.txt.')
 hashes={name:sha(payload) if isinstance(payload,bytes) else sha_file(payload) for name,payload in sorted(entries.items())}
 manifest=''.join(hashes[name]+'  '+name[len(root):]+'\n' for name in sorted(entries)).encode()
 content=dict(entries);content[manifest_name]=manifest
 hashes[manifest_name]=sha(manifest)
 fd,name=tempfile.mkstemp(prefix='.'+destination.name+'-',dir=destination.parent)
 try:
  with os.fdopen(fd,'w+b') as output:
   with zipfile.ZipFile(output,'w',zipfile.ZIP_DEFLATED,compresslevel=6,allowZip64=True) as archive:
    for entry,payload in sorted(content.items()):
     info=zipfile.ZipInfo(entry);info.compress_type=zipfile.ZIP_DEFLATED
     info.external_attr=(0o100600 if '/signing/' in entry else 0o100644)<<16
     info.file_size=len(payload) if isinstance(payload,bytes) else payload.stat().st_size
     digest=hashlib.sha256()
     with archive.open(info,'w') as target:
      if isinstance(payload,bytes):
       target.write(payload);digest.update(payload)
      else:
       with payload.open('rb') as input:
        while True:
         chunk=input.read(CHUNK_BYTES)
         if not chunk:break
         target.write(chunk);digest.update(chunk)
     require(digest.hexdigest()==hashes[entry],'Source changed while packaging: '+entry)
   output.flush();os.fsync(output.fileno())
  temporary=Path(name)
  with zipfile.ZipFile(temporary) as archive:require(archive.testzip() is None,'Source archive ZIP CRC check failed.')
  return {'temporary_path':temporary,'bytes':temporary.stat().st_size,'sha256':sha_file(temporary),'entries':len(content)}
 except BaseException:
  if os.path.exists(name):os.unlink(name)
  raise

