 p=Path(__file__).resolve().parents[1]
 version=json.loads((p/'version.json').read_text());VERSION=version['name'];VERSION_CODE=version['code']
 workspace=p.parents[1]
 out=workspace/'output';out.mkdir(exist_ok=True)
